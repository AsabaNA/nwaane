// Builds the two files Cloudflare D1 needs from the live SQLite database:
//   cloudflare/schema.sql  — tables only (empty), for a fresh deploy
//   cloudflare/data.sql    — the schema plus all rows as INSERTs, to move an existing database
// Run:  DB=school.db node cloudflare/make-d1.js
const fs=require('fs'),path=require('path'),{db}=require('../db');
const q=v=>v===null?'NULL':typeof v=='number'||typeof v=='bigint'?String(v):"'"+String(v).replace(/'/g,"''")+"'";
const objs=db.prepare("SELECT type,name,tbl_name,sql FROM sqlite_master WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' ORDER BY CASE type WHEN 'table' THEN 0 WHEN 'index' THEN 1 ELSE 2 END,rowid").all();
const ddl=objs.map(o=>o.sql.replace(/^CREATE (TABLE|INDEX|TRIGGER|UNIQUE INDEX)/,'CREATE $1 IF NOT EXISTS').replace(/IF NOT EXISTS IF NOT EXISTS/,'IF NOT EXISTS')+';');
const head='-- generated by cloudflare/make-d1.js '+new Date().toISOString()+'\n';
fs.writeFileSync(path.join(__dirname,'schema.sql'),head+ddl.join('\n')+'\n');
let d=head+ddl.join('\n')+'\n';
for(const o of objs.filter(o=>o.type=='table')){const rows=db.prepare(`SELECT * FROM ${o.name}`).all();for(const r of rows){const k=Object.keys(r);d+=`INSERT INTO ${o.name}(${k.join(',')}) VALUES(${k.map(c=>q(r[c])).join(',')});\n`}}
fs.writeFileSync(path.join(__dirname,'data.sql'),d);
console.log('schema.sql: '+ddl.length+' statements; data.sql: '+d.split('\n').length+' lines')
